#!/usr/bin/env python3
"""MECHFALL // FORGE 77 — single source of truth generator.

Reads the JSON data files at the repository root and emits:

  * test_build.html          — the playable, fully self-contained browser prototype
  * cet_mod/.../init.lua     — the CET-only CP2077 test mod (from tools/init.lua.template)
  * ROSTER.md                — the prefab/teardown library reference
  * (compat.json is embedded into both the HTML data bundle and the CET Lua data)
  * docs/BaseModHooks.md     — appendix with generated roster/reactor identifiers

The JSON files are authoritative: never hand-edit generated outputs, re-run this
script instead.  ``python3 tools/generate.py --check`` compares generated bytes
with the files on disk and fails on drift (used by tools/validate.py and CI).
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / "tools"
SRC = TOOLS / "src"
DATA_FILES = ("simulation.json", "reactors.json", "subsystems.json", "chassis.json",
              "components.json", "teardowns.json", "compat.json")
LUA_OUT = ROOT / "cet_mod/bin/x64/plugins/cyber_engine_tweaks/mods/mechfall_forge/init.lua"

# A stable stamp: derived from the data, not the wall clock, so --check is deterministic.
BUILD_DATE = "2026-11-03"


def load_json(name: str):
    return json.loads((ROOT / name).read_text(encoding="utf-8"))


def data_bundle() -> dict:
    d = {name[:-5]: load_json(name) for name in DATA_FILES}
    d["meta"] = {
        "name": "MECHFALL // FORGE 77",
        "build": BUILD_DATE,
        "generator": "tools/generate.py",
        "disclaimer": "Browser + CET prototype. No ripped assets, no base-mod files.",
        "tabs": ["HANGAR", "TEARDOWN", "REACTOR LAB", "INTERNAL SYSTEMS", "MECH FORGE", "COMBAT TEST", "PROCEDURAL PILOT", "DOSSIER", "SETTINGS"],
    }
    return d


def json_for_html(d: dict) -> str:
    """JSON safe to embed in a <script type=application/json> block."""
    return (json.dumps(d, separators=(",", ":"), ensure_ascii=False)
            .replace("<", "\\u003c").replace(">", "\\u003e")
            .replace("&", "\\u0026").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))


def read_js() -> str:
    files = sorted(SRC.glob("*.js"))
    if not files:
        raise SystemExit("no JS sources found in tools/src")
    chunks = []
    for f in files:
        code = f.read_text(encoding="utf-8").rstrip()
        chunks.append("/* ===== %s ===== */\n%s" % (f.name, code))
    return "\n\n".join(chunks) + "\n"


def build_html(d: dict) -> str:
    tpl = (ROOT / "test_build.template.html").read_text(encoding="utf-8")
    css = (SRC / "app.css").read_text(encoding="utf-8")
    body = (SRC / "body.html").read_text(encoding="utf-8")
    out = (tpl.replace("/*__MF_CSS__*/", css)
              .replace("<!--__MF_BODY__-->", body)
              .replace("/*__MF_DATA__*/", json_for_html(d))
              .replace("/*__MF_JS__*/", read_js()))
    for marker in ("__MF_CSS__", "__MF_BODY__", "__MF_DATA__", "__MF_JS__"):
        if marker in out:
            raise SystemExit("unreplaced marker " + marker)
    return out


# --------------------------------------------------------------------------- Lua
def lua_str(s: str) -> str:
    out = []
    for ch in str(s):
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append("\\u{%x}" % o)
    return '"' + "".join(out) + '"'


def lua_value(v, indent=0) -> str:
    pad = "  " * indent
    inner = "  " * (indent + 1)
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        if isinstance(v, float) and v != int(v):
            return repr(round(v, 6))
        return str(int(v))
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, (list, tuple)):
        if not v:
            return "{}"
        lines = [lua_value(x, indent + 1) for x in v]
        return "{\n" + ",\n".join(inner + x for x in lines) + "\n" + pad + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        lines = []
        for k, x in v.items():
            lines.append(inner + "[" + lua_str(k) + "] = " + lua_value(x, indent + 1))
        return "{\n" + ",\n".join(lines) + "\n" + pad + "}"
    raise TypeError(type(v))


def lua_data(d: dict) -> dict:
    """Compact, ASCII-safe subset of the JSON data for the CET UI."""
    chassis = d["chassis"]["roster"]
    return {
        "build": BUILD_DATE,
        "roster": [
            {
                "id": c["id"], "name": c["name"], "faction": c["faction"],
                "archetype": c["archetype"], "role": c["role"],
                "reactorId": c["reactorId"], "hardpoints": c["hardpoints"],
                "aliases": ", ".join(c["aliases"]),
                "shape": c["shape"], "subsystems": c["subsystems"],
            }
            for c in chassis
        ],
        "reactors": [{"id": p["id"], "name": p["name"], "params": p["params"]} for p in d["reactors"]["presets"]],
        "subsystemTemplates": [
            {"id": s["id"], "name": s["name"], "category": s["category"], "params": s["params"]}
            for s in d["subsystems"]["templates"]
        ],
        "coefficientDefaults": {k: v["value"] for k, v in d["simulation"]["coefficients"].items()},
        "biomes": {k: v["multiplier"] for k, v in d["reactors"]["biomes"].items()},
        "compat": {
            "autodrive": {
                "modNames": d["compat"]["autodrive"]["modNames"],
                "handoffMethods": d["compat"]["autodrive"]["handoffMethods"],
                "key": d["compat"]["autodrive"]["key"],
            },
            "crystalCoat": {
                "modNames": d["compat"]["crystalCoat"]["modNames"],
                "syncMethods": d["compat"]["crystalCoat"]["syncMethods"],
                "aspects": d["compat"]["crystalCoat"]["aspects"],
                "codeExample": d["compat"]["crystalCoat"]["codeExample"],
                "fields": d["compat"]["crystalCoat"]["fields"],
            },
            "coatings": d["compat"]["coatings"],
        },
    }


def build_lua(d: dict) -> str:
    tpl = (TOOLS / "init.lua.template").read_text(encoding="utf-8")
    table = "-- AUTO-GENERATED by tools/generate.py — DO NOT EDIT\nreturn " + lua_value(lua_data(d)) + "\n"
    out = tpl.replace("--__MF_GENERATED_DATA__", table)
    if "__MF_GENERATED_DATA__" in out:
        raise SystemExit("unreplaced Lua data marker")
    return out


# --------------------------------------------------------------------------- Roster docs
def build_roster(d: dict) -> str:
    c = d["chassis"]
    reactors = {p["id"]: p["name"] for p in d["reactors"]["presets"]}
    lines = [
        "# Prefab / teardown library",
        "",
        "> Generated by `tools/generate.py` from `chassis.json`. **Do not edit by hand.**",
        "> Prefabs are deployable examples, teardown source material and shape/part templates —",
        "> **not** the headline. The point of FORGE 77 is fully custom chassis and player-authored",
        "> internal subsystems. Names are canonical with aliases recorded; no ripped models or assets.",
        "",
        "| Faction | Role in the sandbox |",
        "|---|---|",
    ]
    for f, info in c["factions"].items():
        lines.append("| %s | %s |" % (f, info["role"]))
    lines += ["", "## Roster (%d chassis, 6 factions)" % len(c["roster"]), "",
              "| # | Canonical name | Aliases | Faction | Archetype | Role | Reactor | HPs | Salvage | XP |",
              "|---:|---|---|---|---|---|---|---:|---:|---:|"]
    for i, x in enumerate(c["roster"], 1):
        lines.append("| %d | %s | %s | %s | %s | %s | %s | %d | %d | %d |" % (
            i, x["name"], ", ".join(x["aliases"]), x["faction"], x["archetype"], x["role"],
            reactors.get(x["reactorId"], x["reactorId"]), x["hardpoints"], x["salvage"], x["xp"]))
    lines += ["", "## Signature parts", "",
              "Each chassis composes original procedural parts inspired by the characteristic components "
              "of the study materials (cockpit pods, skull heads, missile racks, ether wings, reverse-joint "
              "legs, hover discs, blade arms, crests, shields). See `chassis.json → signatureParts` and "
              "`docs/AssetManifest.md`. No third-party geometry is imported.", ""]
    lines += ["", "## Procedural 3D pilot and optional compatibility", "",
              "The `PILOT TEST` tab triangulates these shapes into a playable procedural 3D mech "
              "(mesh, terrain, gait and coating generated at runtime). `compat.json` defines the "
              "optional Autodrive waypoint solver and Crystal-Coat-compatible CCP1 share codes. "
              "See `docs/PROCEDURAL_PILOT.md` and `docs/COMPAT.md`.", ""]
    lines += ["", "## Shape parameters (source material for the modeling table)", "",
              "Every chassis carries a 20-parameter shape vector plus a `sig` signature-part composition that can be loaded into MECH FORGE:",
              "", "`" + ", ".join(c["shapeKeys"]) + "`", "",
              "Spelling variations resolved: Earlcumber/Erlecumber, Tzendolg/Tzendolimble, Toybox/Toy Box.",
              "See `HANDOVER.md` §3.6 and `PERMISSIONS.md` for IP carve-outs.", ""]
    return "\n".join(lines)


def build_hooks_appendix(d: dict) -> str:
    ids = [c["id"] for c in d["chassis"]["roster"]]
    reactors = [p["id"] for p in d["reactors"]["presets"]]
    return ("\n## Generated identifiers (for CET snippets)\n\n"
            "- Chassis ids: `" + "`, `".join(ids) + "`\n"
            "- Reactor preset ids: `" + "`, `".join(reactors) + "`\n")


# --------------------------------------------------------------------------- main
def outputs(d: dict) -> dict:
    return {
        ROOT / "test_build.html": build_html(d),
        ROOT / "ROSTER.md": build_roster(d),
        LUA_OUT: build_lua(d),
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    ap.add_argument("--print-roster", action="store_true", help="print ROSTER.md to stdout")
    args = ap.parse_args(argv)
    d = data_bundle()
    gen = outputs(d)
    if args.print_roster:
        print(gen[ROOT / "ROSTER.md"], end="")
        return 0
    stale = []
    for path, content in gen.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if current != content:
                path.write_text(content, encoding="utf-8")
            print("generated %-70s %7d bytes" % (str(path.relative_to(ROOT)), len(content.encode())))
    if args.check:
        if stale:
            print("STALE generated files (run python3 tools/generate.py):", file=sys.stderr)
            for s in stale:
                print("  - " + s, file=sys.stderr)
            return 1
        print("OK: all generated outputs are up to date (%d files)" % len(gen))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
