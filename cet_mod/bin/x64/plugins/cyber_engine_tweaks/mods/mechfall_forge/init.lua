registerForEvent("onDraw", function()
  if not MF.visible then return end
  if not ImGui.Begin("MECHFALL // FORGE 77 · CET TEST UI") then ImGui.End(); return end
  for i, name in ipairs(MF.tabs) do
    if ImGui.Button(name .. "##tab" .. i) then MF.tab = i end
    if i < #MF.tabs then ImGui.SameLine() end
  end
  ImGui.Separator()
  local ok, t = pcall(MF.compute, MF.activeDesignId)
  if not ok then
    ImGui.Text("Telemetry error: " .. tostring(t))
    ImGui.End()
    return
  end
  if MF.tab == 1 then drawHangar(t)
  elseif MF.tab == 2 then drawSystems(t)
  elseif MF.tab == 3 then drawForge(t)
  elseif MF.tab == 4 then drawReactor(t)
  elseif MF.tab == 5 then drawSettings()
  elseif MF.tab == 6 then drawCompat()
  else drawIngame(t) end
  ImGui.End()
end)

