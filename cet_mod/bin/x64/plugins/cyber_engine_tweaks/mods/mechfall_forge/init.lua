      MF.subIndex = #MF.subsystems
      log("Created blank-slate subsystem (six attributes are directly editable)")
    end
    ImGui.SameLine()
    if ImGui.Button("PRINT CET LUA SNIPPET") then
      print("[MECHFALL] -- snippet for MF.customDesigns[...].subsystems")
      print("[MECHFALL] { id = \"" .. s.id .. "\", name = \"" .. s.name .. "\", category = \"" ..
        s.category .. "\", six = { powerDraw = " .. f(x.powerDraw, 3) .. ", mass = " .. f(x.mass, 3) ..
        ", heatGen = " .. f(x.heatGen, 3) .. ", heatDiss = " .. f(x.heatDiss, 3) ..
        ", rcs = " .. f(x.rcs, 3) .. ", ecm = " .. f(x.ecm, 3) .. " } }")
    end
