    local emissions = jam * (lpi > 0 and 0.25 or 1) * (emcon > 0 and 0.05 or 1) + spoof * 8 + chaff * 0.2
    o.powerDraw = 3 + jam * 0.85 + band * 8 + spoof * 6 - (emcon > 0 and 2 or 0)
