-- Continuous input ----------------------------------------------------------
function IG.input(action, pressed)
  IG.keys[action] = pressed and true or false
  if not pressed then return end
  if action == "deploy" then if IG.active then IG.undeploy() else IG.deploy() end
  elseif action == "reset" then IG.undeploy()
  elseif action == "jump" then IG.jump()
  elseif action == "vent" then IG.vent()
  elseif action == "fire" then IG.fire()
  elseif action == "camera" then IG.cycleCamera()
  elseif action == "autodrive" then IG.toggleAutopilot()
  elseif action == "forward" or action == "back" then IG.autopilot = false
  end
end

-- Camera target for the cockpit lock (x/y are ground plane, z is height). ----
local function cameraTarget()
  local s, c = math.sin(IG.yaw), math.cos(IG.yaw)
  local x, y, z = IG.pos.x, IG.pos.y, IG.pos.z
  if IG.cameraMode == "COCKPIT" then
    return x + s * 0.8, y + c * 0.8, z + IG.ph.cockpitHeight
  elseif IG.cameraMode == "ORBIT" then
    return x + c * IG.ph.orbitRadius, y - s * IG.ph.orbitRadius, z + IG.ph.orbitHeight
  end
  return x - s * IG.ph.chaseDistance, y - c * IG.ph.chaseDistance, z + IG.ph.chaseHeight
end

-- Per-frame update: read keys, apply engineering consequences, move entities,
-- lock V to the cockpit, and let RCS/ECM spawn or break real in-world locks.
function IG.update(delta)
  if not IG.active then return end
  if not inPlay() then IG.undeploy(); return end
  local dt = clamp(tonumber(delta) or 0.016, 0, IG.ph.maxFrameDt)
  if dt <= 0 then return end
  IG.clock = IG.clock + dt
  IG.lastTelemetry = IG.lastTelemetry + dt
  IG.venting = math.max(0, IG.venting - dt)

  if IG.lastTelemetry >= 1 / math.max(0.2, IG.ph.telemetryHz) then
    IG.lastTelemetry = 0
    pcall(function() IG.telemetry = MF.compute(MF.activeDesignId) end)
  end
  local t = IG.telemetry or {}
  local powerMargin = tonumber(t.powerMargin) or 0
  local temp = tonumber(t.temperature) or 0.34
  local netHeat = tonumber(t.netHeat) or 0
  local rcs = tonumber(t.rcsFront) or 10
  local jam = tonumber(t.jamStrength) or 0
  local emissions = tonumber(t.selfEmissions) or 0
  local speed = tonumber(t.speed) or IG.ph.walkSpeed
  local brownout = powerMargin < 0 and 0.45 or 1
  local derate = temp > 0.72 and 0.6 or 1
  IG.heat = clamp(IG.heat + netHeat * dt * 0.0015, 0.2, 1.6)

  -- steering: manual keys or procedural autodrive toward a waypoint
  local steer = (IG.keys.right and 1 or 0) - (IG.keys.left and 1 or 0)
  local throttle = 0
  if IG.autopilot then
    local dx, dy = IG.pos.x - IG.waypoint.x, IG.pos.y - IG.waypoint.y
    if (dx * dx + dy * dy) < 36 then
      IG.autopilot = false
      iglog("AUTODRIVE — waypoint reached")
    else
      local want = math.atan2(-dx, -dy)
      local diff = want - IG.yaw
      while diff > math.pi do diff = diff - 2 * math.pi end
      while diff < -math.pi do diff = diff + 2 * math.pi end
      steer = clamp(diff * 1.6, -1, 1)
      throttle = 0.55 * (1 - math.min(0.6, math.abs(diff) / math.pi))
    end
  else
    if IG.keys.forward then throttle = throttle + 1 end
    if IG.keys.back then throttle = throttle - 0.6 end
  end
  IG.yaw = IG.yaw + steer * IG.ph.turnRate * dt * brownout
  local sp = speed * brownout * derate * throttle * (IG.keys.dash and (IG.ph.dashSpeed / math.max(1, speed)) or 1)
  IG.pos.x = IG.pos.x + math.sin(IG.yaw) * sp * dt
  IG.pos.y = IG.pos.y + math.cos(IG.yaw) * sp * dt
  IG.vy = IG.vy - IG.ph.gravity * dt
  IG.pos.z = math.max(IG.baseZ, IG.pos.z + IG.vy * dt)
  if IG.pos.z <= IG.baseZ then IG.vy = 0 end
  IG.gait = IG.gait + dt * IG.ph.gaitRate * (math.abs(sp) > 0.2 and 1 or 0.2)
  local d = yawDeg(IG.yaw)

  -- core chassis follows the pilot state
  if IG.coreId and not IG.core then IG.core = resolve(IG.coreId) end
  if IG.core then
    local bob = math.sin(IG.gait) * IG.ph.gaitAmplitude * (math.abs(sp) > 0.2 and 1 or 0)
    if not moveEntity(IG.core, IG.pos.x, IG.pos.y, IG.pos.z + bob, d) then IG.core = nil end
  end
  -- signature parts orbit / gait around the chassis
  for i, p in ipairs(IG.parts or {}) do
    if not p.entity then p.entity = resolve(p.id) end
    if p.entity then
      local off = rotated(p.off, IG.yaw)
      local bob = math.sin(IG.gait + p.off.phase) * IG.ph.gaitAmplitude
      if not moveEntity(p.entity, IG.pos.x + off.x, IG.pos.y + off.y,
        IG.pos.z + off.z + bob, d + i * 11) then p.entity = nil end
    end
  end
  for _, id in ipairs(IG.templateIds or {}) do
    local e = resolve(id)
    if e then moveEntity(e, IG.pos.x, IG.pos.y, IG.pos.z, d) end
  end

  -- cockpit lock: throttled Teleport so the game camera rides the mech
  if IG.cockpitLock and IG.clock - IG.lastTeleport >= 1 / math.max(5, IG.ph.updateHz) then
    IG.lastTeleport = IG.clock
    local cx, cy, cz = cameraTarget()
    local ok, err = pcall(function()
      local p = Game.GetPlayer()
      if not p then return end
      local tp = Game.GetTeleportationFacility()
      if tp then tp:Teleport(p, vec(cx, cy, cz), euler(d)) end
    end)
    if not ok then
      IG.lastError = tostring(err)
      IG.cockpitLock = false
      iglog("Cockpit lock disabled after teleport error: " .. IG.lastError)
    end
  end

  -- RCS / ECM / jamming consequences in the actual game world
  if IG.showThreats and IG.clock - IG.lastThreat >= IG.ph.threatInterval then
    IG.lastThreat = IG.clock
    local risk = rcs / 14 + emissions / 30 + (IG.venting > 0 and 0.4 or 0) - jam / 40
    if risk > 0.9 and IG.api.spawnRecord then
      IG.spawnHostile()
    elseif risk < 0.35 and #IG.hostiles > 0 then
      IG.breakLock()
    else
      iglog("SIGNATURE " .. f(risk, 2) .. " · RCS " .. f(rcs, 1) .. " · ECM " .. f(jam, 1) ..
        " · power " .. f(powerMargin, 1) .. " kW · heat " .. f(IG.heat, 2))
    end
  end
end

