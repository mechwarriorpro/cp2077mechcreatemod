  ImGui.EndChild()
  ImGui.Separator()
  bar("POWER MARGIN", t.powerMargin, 120, "kW")
  bar("HEAT DISSIPATION", t.heatDiss, 120, "kW")
  bar("ECM STRENGTH", t.jamStrength, 80, "str")
end

local function drawForge(t)
  local d = t.design
  ImGui.Text("MECH FORGE · parametric shape (browser owns the visual modeling table)")
  ImGui.Separator()
  local shape = d.shape or {}
  local keys = { "torsoW", "torsoH", "torsoD", "headScale", "shoulderW", "shoulderH",
    "upperArm", "foreArm", "upperLeg", "lowerLeg", "hipW", "footL", "weaponX",
    "weaponY", "legStance", "armorFlare", "jetCount" }
  for _, k in ipairs(keys) do
    local min, max = 0.2, 4.6
    if k == "jetCount" then min, max = 0, 8 end
    if k == "armorFlare" then min, max = 0, 1.8 end
    if k == "headScale" then min, max = 0.2, 1.6 end
    local v = { tonumber(shape[k]) or min }
    local nv, changed = ImGui.SliderFloat(k .. "##shape", v[1], min, max, "%.2f")
    if changed then shape[k] = nv end
  end
  d.shape = shape
  if ImGui.Button("BAKE SHAPE INTO CUSTOM DESIGN") then
    local c = MF.customDesigns[1]
    c.shape = {}
    for k, v in pairs(shape) do c.shape[k] = v end
    MF.activeDesignId = c.id
    log("Baked shape into " .. c.name)
  end
  ImGui.SameLine()
  if ImGui.Button("SEND REACTOR TO FORGE") then log("Reactor parameters applied to active design") end
  ImGui.Separator()
  ImGui.Text("SPEED " .. f(t.speed, 2) .. " m/s · MASS " .. f(t.totalMass, 0) .. " kg")
  ImGui.Text("CoM " .. f(t.comOffset, 3) .. " · STRESS " .. f(t.stress, 2))
  ImGui.Text("VALIDATION: " .. (#t.validation == 0 and "NOMINAL" or table.concat(t.validation, ", ")))
end

local function drawReactor(t)
  ImGui.Text("MANA REACTOR · power source, one subsystem among many")
  local r = MF.reactor
  local sliders = {
    { "F", 0, 12 }, { "G", 0, 12 }, { "A", 0, 12 }, { "eta", 0.05, 0.99 },
    { "S", 0.2, 3.2 }, { "Q", 1, 5 }, { "C", 0, 0.98 }, { "W", 0.05, 4 }, { "L", 0, 1 }
  }
  for _, q in ipairs(sliders) do
    local v = { tonumber(r[q[1]]) or q[2] }
    local nv, changed = ImGui.SliderFloat(q[1] .. "##rx", v[1], q[2], q[3], "%.2f")
    if changed then r[q[1]] = nv end
  end
  ImGui.Separator()
  local pr = MF_DATA.reactors or {}
  if #pr > 0 then
    local names = {}
    for j, p in ipairs(pr) do names[j] = p.name end
    local idx, ch = ImGui.Combo("PRESET##rx", MF.reactorPresetIndex - 1, names, #pr)
    if ch then
      MF.reactorPresetIndex = idx + 1
      local p = pr[MF.reactorPresetIndex].params
      for k, v in pairs(p) do r[k] = v end
      log("Reactor preset: " .. pr[MF.reactorPresetIndex].name)
    end
  end
  local rm = reactorModel(r)
  bar("NET OUTPUT", rm.netOutput, 250, "kW")
  bar("INSTABILITY", rm.instability, 1.5, "")
  bar("HEAT LOAD", rm.heatLoad, 60, "kW")
  ImGui.Text("Crystal signature " .. f(rm.crystalSignature, 2) .. " m2 · doubling S = " ..
    f(2 ^ MF.rcoeffs.sizeExponent, 2) .. "x power / " ..
    f(2 ^ MF.rcoeffs.instabilitySizeExponent, 2) .. "x instability")
  if rm.meltdown then ImGui.TextColored(1, 0.3, 0.3, 1, "CONTAINMENT FAILURE / MELTDOWN") end
end

local function drawSettings()
  ImGui.Text("CONFIG · exponents are never hard-coded")
  local v, ch = ImGui.Checkbox("TEST MODE (deploy with penalties)", MF.testMode)
  if ch then MF.testMode = v end
  v, ch = ImGui.Checkbox("UNLOCK ALL (TEST MODE)", MF.unlockAll)
  if ch then MF.unlockAll = v end
  v, ch = ImGui.Checkbox("ALLOW INVALID DEPLOY", MF.allowInvalidDeploy)
  if ch then MF.allowInvalidDeploy = v end
  ImGui.Separator()
  for _, k in ipairs({ "k1", "k2", "massRef", "baseSpeed", "rcsShapeExponent",
    "rcsMaterialExponent", "detectionK", "jamK", "ecmFalloffExponent", "enemySensorFactor" }) do
    local val = { tonumber(MF.coeffs[k]) or 1 }
    local lo, hi = 0, 400
    if k == "k1" or k == "k2" then lo, hi = 0, 1 end
    if k == "rcsShapeExponent" then lo, hi = 0.5, 3 end
    if k == "ecmFalloffExponent" then lo, hi = 1, 3.5 end
    local nv, c = ImGui.SliderFloat(k .. "##co", val[1], lo, hi, "%.2f")
    if c then MF.coeffs[k] = nv end
  end
  ImGui.Separator()
  ImGui.Text("OPTIONAL BASE-MOD HOOKS (pcall-wrapped, never required)")
  if ImGui.Button("RESTART BT QUEST") then MF.optionalRestartQuest() end
  ImGui.SameLine()
  if ImGui.Button("TITAN POINTS +5") then MF.optionalTitanPoints() end
  ImGui.Separator()
  textWrapped("Browser prototype + CET UI is testable. A full 3D pilotable-mech release needs meshes, " ..
    "rigs, animations, VO, the game itself and private base-mod APIs. No base-mod files are bundled.")
  ImGui.Separator()
  ImGui.Text("EVENT LOG")
  ImGui.BeginChild("mf_log", -1, 90)
  for _, line in ipairs(MF.log) do ImGui.Text(line) end
  ImGui.EndChild()
end

registerForEvent("onInit", function()
  MF.visible = false
  log("MECHFALL // FORGE 77 loaded · " .. tostring(#(MF_DATA.roster or {})) .. " prefabs, " ..
    tostring(#MF.subsystems) .. " subsystem templates")
  log("Open the overlay with the CET hotkey binding: MECHFALL // FORGE 77")
end)

registerForEvent("onDraw", function()
  if not MF.visible then return end
  if not ImGui.Begin("MECHFALL // FORGE 77 · CET TEST UI") then ImGui.End(); return end
  for i, name in ipairs(MF.tabs) do
    if ImGui.Button(name .. "##tab" .. i) then MF.tab = i end
    if i < #MF.tabs then ImGui.SameLine() end
  end
  ImGui.Separator()
  local ok, t = pcall(MF.compute, MF.activeDesignId)
  if not ok then
    ImGui.Text("Telemetry error: " .. tostring(t))
    ImGui.End()
    return
  end
  if MF.tab == 1 then drawHangar(t)
  elseif MF.tab == 2 then drawSystems(t)
  elseif MF.tab == 3 then drawForge(t)
  elseif MF.tab == 4 then drawReactor(t)
  else drawSettings() end
  ImGui.End()
end)

