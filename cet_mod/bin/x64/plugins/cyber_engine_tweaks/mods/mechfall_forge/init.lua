-- Reactor model (same equations as the browser) -----------------------------
MF.reactor = {
  F = 4.0, G = 5.2, A = 4.0, eta = 0.72, S = 1.0, Q = 2.0, C = 0.74, W = 1.2, L = 0.8
}
local function reactorModel(p)
  local m = MF.rcoeffs
  local rawHarvest = p.A * MF.biomeMultiplier * p.L
  local pool = math.max(0, (p.G - p.F) * 5 + rawHarvest)
  local throughput = clamp(math.min(p.F, pool + rawHarvest), 0, p.F)
  local grossMana = throughput * p.eta * (p.S ^ m.sizeExponent) * (1 + m.gradeBonus * (p.Q - 1))
  local gross = grossMana * m.outputScale
  local heatLoad = (throughput / math.max(p.W, 0.05)) * p.eta * (1 - p.eta) * m.heatLoadFactor
    * (1 + m.gradeBonus * (p.Q - 1))
  local instability = (p.S / m.S_ref) ^ m.instabilitySizeExponent * (p.F / m.F_ref) ^ m.instabilityFlowExponent
    * (1 - p.eta) * (1 - p.C) * (1 + heatLoad)
  local net = gross * (1 - math.min(instability, 1) * m.derateFactor)
  local crystalSig = m.signatureFactor * (p.S ^ (m.instabilitySizeExponent * 0.75)) * (1 - p.eta * 0.45)
  return { netOutput = net, grossOutput = gross, instability = instability, heatLoad = heatLoad,
    heat = gross * (1 - p.eta) * 0.12 + heatLoad * 8 + instability * 5,
    crystalSignature = crystalSig, rawHarvest = rawHarvest, meltdown = instability > 1.0 }
end
MF.reactorModel = reactorModel

-- Full design telemetry -----------------------------------------------------
function MF.compute(designId)
  local d = designById(designId or MF.activeDesignId) or MF.customDesigns[1]
  local r = reactorModel(MF.reactor)
  local parasitic = 3.5 + r.netOutput * 0.045 + (MF.reactor.W or 1.2) * 1.6 + (MF.reactor.C or 0.74) * 2
  local used, mass, hg, hd, rcs, ecm = parasitic, 0, r.heat, 0, r.crystalSignature, 0
  local comOffset, stress, jamBase, emissions, speedBoost = 0, 0.3, 0, 0, 1
  local rcsMult, ewHeat, transmissionLoss, thermalExtra, mat, arm = 1, 0, 0.08, 0, 1.28, 1.1
  for _, id in ipairs(d.subsystemIds or {}) do
    local s = subById(id)
    if s then
      local x = derive(s)
      used = used + (x.powerDraw or 0)
      mass = mass + (x.mass or 0)
      hg = hg + (x.heatGen or 0)
      hd = hd + (x.heatDiss or 0)
      rcs = rcs + (x.rcs or 0)
      ecm = ecm + (x.ecm or 0)
      if s.category == "ecm_ew" then ewHeat = x.heatGen or 0 end
      if s.category == "thermal_loop" then
        local pp = s.params or {}
        thermalExtra = 60 + (tonumber(pp.phaseChangeMass) or 18) * 4 + (tonumber(pp.insulation) or 0.3) * 30
      end
      if s.category == "power_bus" then
        local pp = s.params or {}
        local gauge, volts, ground = tonumber(pp.conduitGauge) or 8, tonumber(pp.voltage) or 120, tonumber(pp.grounding) or 0.7
        transmissionLoss = clamp(0.15 - gauge * 0.004 - volts / 6000 + (1 - ground) * 0.06, 0.012, 0.34)
      end
      if x.extra then
        comOffset = comOffset + (x.extra.comOffset or 0)
        stress = math.max(stress, x.extra.stress or 0)
        jamBase = jamBase + (x.extra.jamBase or 0)
        emissions = emissions + (x.extra.emissions or 0)
        speedBoost = speedBoost * (x.extra.speed or 1)
        rcsMult = x.extra.rcsMultiplier or rcsMult
        mat = x.extra.mat or mat
        arm = x.extra.armourDensity or arm
      end
    end
  end
  local shape = d.shape or {}
  local sf = ({ angular = 1.0, rounded = 0.94, knight = 1.18, spider = 1.28, tetrapod = 1.34 })[shape.style] or 1.0
  local shapeVolume = ((shape.torsoW or 2.4) * (shape.torsoH or 2.8) * (shape.torsoD or 1.7) * 0.32
    + (shape.shoulderW or 2.2) * (shape.shoulderH or 0.8) * 0.7
    + ((shape.upperArm or 1.5) + (shape.foreArm or 1.7)) * 0.28
    + ((shape.upperLeg or 1.9) + (shape.lowerLeg or 2.0)) * 0.34
    + (shape.hipW or 1.7) * 0.4 + (shape.footL or 1.3) * 0.25
    + (shape.armorFlare or 0.5) * 0.5) * sf
  local frameMass = shapeVolume * (MF.coeffs.shapeMassFactor or 75) * mat * (0.6 + arm * 0.4)
  -- The reactor is a subsystem too: add its mass, cooling and damping contribution.
  mass = mass + (120 + (MF.reactor.S or 1) * 95 + (MF.reactor.C or 0.74) * 60 + (MF.reactor.Q or 2) * 8)
  hd = hd + (2 + (MF.reactor.W or 1.2) * 6)
  ecm = ecm + (0.4 + (1 - (MF.reactor.C or 0.74)) * 2)
  local totalMass = frameMass + mass + frameMass * 0.22 + (d.hardpoints or 6) * 18
  local usedEff = used * (1 + transmissionLoss)
  local powerMargin = r.netOutput - usedEff
  hg = hg + ewHeat * 0.35
  local heatDiss = math.max(0, hd)
  local netHeat = hg - heatDiss
  local thermalMass = 140 + totalMass * (MF.coeffs.thermalMassFactor or 6) / 12 + thermalExtra
  local temp = clamp(0.32 + netHeat / math.max(heatDiss, 6) * 0.42, 0, 1.8)
  local shapeFactor = (((shape.torsoW or 2.4) * 0.8 + (shape.legStance or 1.3) * 0.7
    + (shape.shoulderW or 2.2) * 0.5 + (shape.armorFlare or 0.5) * 0.4 + 1)
    ^ (MF.coeffs.rcsShapeExponent or 1.35)) * 0.35 + 1.2
  local materialFactor = rcsMult ^ (MF.coeffs.rcsMaterialExponent or 0.85)
  local frontRcs = clamp((shapeFactor * materialFactor + rcs
    + emissions * (MF.coeffs.emissionRcsFactor or 0.12)) * 0.78, 0.35, 500)
  local detect = (MF.coeffs.detectionK or 120) * (frontRcs ^ (MF.coeffs.detectionExponent or 0.5))
    * (MF.coeffs.enemySensorFactor or 1)
  local jam = (MF.coeffs.jamK or 240) / 100 * jamBase / 1.5
  local speed = math.max(0.8, (MF.coeffs.baseSpeed or 9) *
    (1 - (MF.coeffs.k1 or 0.34) * totalMass / (MF.coeffs.massRef or 2200)) *
    (1 - (MF.coeffs.k2 or 0.25) * stress) * speedBoost)
  comOffset = comOffset + ((shape.weaponX or 1.5) - (shape.torsoW or 2.4)) * 0.015
  local validation = {}
  if powerMargin < 0 then table.insert(validation, "BROWNOUT") end
  if netHeat > 0 and temp > 0.72 then table.insert(validation, "THERMAL SATURATION") end
  if totalMass / (MF.coeffs.massRef or 2200) > 1.35 then table.insert(validation, "OVER MASS") end
  if math.abs(comOffset) > 0.34 then table.insert(validation, "COM OFFSET") end
  if stress > 0.78 then table.insert(validation, "STRUCTURAL STRESS") end
  if frontRcs > 14 then table.insert(validation, "RCS EXPOSURE") end
  if emissions > 22 then table.insert(validation, "ECM SELF-DETECTION") end
  if r.rawHarvest < 0.22 * math.max(MF.reactor.F, 0.01) then table.insert(validation, "MANA STARVATION") end
  if r.instability > 0.55 then table.insert(validation, "CRYSTAL RESONANCE") end
  if r.instability > 0.95 then table.insert(validation, "CONTAINMENT FAILURE") end
  if r.meltdown then table.insert(validation, "MELTDOWN / PROTOCOL 3") end
  return {
    design = d, reactor = r, powerUsed = usedEff, powerMargin = powerMargin,
    totalMass = totalMass, frameMass = frameMass, netHeat = netHeat, heatGen = hg,
    heatDiss = heatDiss, temperature = temp, thermalMass = thermalMass,
    rcsFront = frontRcs, detectRange = detect, jamStrength = jam,
    selfEmissions = emissions, ecm = ecm, speed = speed, comOffset = comOffset,
    stress = stress, validation = validation
  }
end

