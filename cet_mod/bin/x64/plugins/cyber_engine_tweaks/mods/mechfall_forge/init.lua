local function derive(s)
  if s.six then return s.six end
  local p = s.params or {}
  local o = sixZero()
  local n = function(k, d) return tonumber(p[k]) or d or 0 end
  local c = s.category
  if c == "power_bus" then
    local cap, gauge, volts, red, bank, ground = n("busCapacity", 180), n("conduitGauge", 8),
      n("voltage", 120), n("routingRedundancy", 1), n("capacitorBank", 24), n("grounding", 0.7)
    local loss = clamp(0.15 - gauge * 0.004 - volts / 6000 + (1 - ground) * 0.06, 0.012, 0.34)
    o.powerDraw = 2 + cap * 0.012 + red * 1.4 + bank * 0.03
    o.mass = 24 + cap * 0.22 + gauge * 2.2 + bank * 0.8 + red * 6
    o.heatGen = cap * loss * 0.06 + red * 0.4
    o.heatDiss = 1.5 + gauge * 0.2
    o.rcs = 0.4 + cap * 0.002
    o.ecm = ground * 1.5
  elseif c == "thermal_loop" then
    local ct = ({ 0.75, 1.0, 1.32, 1.55 })[clamp(math.floor(n("coolantType", 1)) + 1, 1, 4)]
    local pump, area, pipes, phase = n("pumpRate", 48), n("radiatorArea", 38), n("heatPipeCount", 14), n("phaseChangeMass", 18)
    local ins = n("insulation", 0.3)
    o.powerDraw = 1 + pump * 0.08 + pipes * 0.05
    o.mass = 18 + area * 1.6 + pipes * 0.7 + phase * 0.9
    o.heatGen = pump * 0.05
    o.heatDiss = (area * 0.58 + pipes * 0.4) * ct * (0.4 + pump / 50) * (1 - ins * 0.35)
    o.rcs = area * 0.062 + (1 - ins) * 0.3
  elseif c == "mass_structure" then
    local arm, cw, hp, off, brace = n("armourDensity", 1.1), n("counterweights", 12),
      n("hardpoints", 4), n("comOffset", 0), n("bracing", 0.55)
    o.mass = arm * 150 + cw + hp * 12 + brace * 40
    o.heatGen = arm * 1.2
    o.heatDiss = -arm * 5.5
    o.rcs = arm * 1.4 + hp * 0.35 + (1 - brace) * 0.3
    local mat = ({ 1.0, 1.28, 0.78, 1.62, 0.7 })[clamp(math.floor(n("frameMaterial", 1)) + 1, 1, 5)]
    o.extra = { comOffset = off - cw / 260,
