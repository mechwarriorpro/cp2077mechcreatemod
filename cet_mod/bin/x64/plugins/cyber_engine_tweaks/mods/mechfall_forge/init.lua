local function sliderParam(s, key, label, min, max, step)
  local v = { tonumber(s.params[key]) or min }
  local nv, changed = ImGui.SliderFloat(label .. "##" .. s.id .. key, v[1], min, max, "%.2f")
  if changed then s.params[key] = nv; s.six = nil; s.six = derive(s) end
end

local function drawSystems(t)
  ImGui.BeginChild("mf_sub_list", 250, 300)
  for i, s in ipairs(MF.subsystems) do
    if ImGui.Selectable(s.name .. "##" .. i, MF.subIndex == i) then MF.subIndex = i end
  end
  ImGui.EndChild()
  ImGui.SameLine()
  ImGui.BeginChild("mf_sub_edit", 380, 300)
  local s = MF.subsystems[MF.subIndex] or MF.subsystems[1]
  if s then
    ImGui.Text("AUTHORING: " .. s.name .. " (" .. s.category .. ")")
    local x = derive(s)
    ImGui.Text("P " .. f(x.powerDraw) .. "  M " .. f(x.mass) .. "  HG " .. f(x.heatGen))
    ImGui.Text("HD " .. f(x.heatDiss) .. "  RCS " .. f(x.rcs) .. "  ECM " .. f(x.ecm))
    ImGui.Separator()
    local params = {
      { "busCapacity", 0, 600 }, { "radiatorArea", 0, 160 }, { "armourDensity", 0, 3 },
      { "ramCoating", 0, 1 }, { "jammerPower", 0, 200 }, { "radarAperture", 0, 12 },
      { "servoCount", 0, 40 }, { "powerDraw", -100, 100 }, { "mass", -500, 1500 },
      { "heatGen", 0, 200 }, { "heatDiss", 0, 200 }, { "rcs", -40, 60 }, { "ecm", -40, 80 }
