    for _, id in ipairs(t.design.subsystemIds or {}) do if id == s.id then installed = true end end
    local val, ch = ImGui.Checkbox("INSTALLED IN ACTIVE DESIGN", installed)
    if ch then
      local ids = t.design.subsystemIds or {}
      if val then
        table.insert(ids, s.id)
      else
