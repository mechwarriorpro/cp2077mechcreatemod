-- Special type constructors, with ToVector4 / ToEulerAngles fallbacks. -------
local function vec(x, y, z)
  if type(Vector4) == "table" and type(Vector4.new) == "function" then
    local ok, v = pcall(function() return Vector4.new(x, y, z, 1.0) end)
    if ok and v then return v end
  end
  if type(ToVector4) == "function" then
    local ok, v = pcall(function() return ToVector4 { x = x, y = y, z = z, w = 1 } end)
    if ok and v then return v end
  end
  return { x = x, y = y, z = z, w = 1 }
end
local function euler(yawDeg)
  local d = yawDeg or 0
  if type(EulerAngles) == "table" and type(EulerAngles.new) == "function" then
    local ok, v = pcall(function() return EulerAngles.new(0, 0, d) end)
    if ok and v then return v end
  end
  if type(ToEulerAngles) == "function" then
    local ok, v = pcall(function() return ToEulerAngles { roll = 0, pitch = 0, yaw = d } end)
    if ok and v then return v end
  end
  return { roll = 0, pitch = 0, yaw = d }
end
local function yawDeg(rad) return (rad or 0) * 180 / math.pi end
-- WorldTransform for spawning; falls back to a copy of the player's transform.
local function worldTransform(x, y, z, deg)
  local made = nil
  if type(WorldTransform) == "table" and type(WorldTransform.new) == "function" then
    pcall(function()
      local tr = WorldTransform.new()
      tr:SetPosition(vec(x, y, z))
      if type(tr.SetOrientationEuler) == "function" then tr:SetOrientationEuler(euler(deg)) end
      made = tr
    end)
  end
  if made then return made end
  pcall(function()
    local p = Game.GetPlayer()
    if not p then return end
    local tr = p:GetWorldTransform()
    tr:SetPosition(vec(x, y, z))
    if type(tr.SetOrientationEuler) == "function" then tr:SetOrientationEuler(euler(deg)) end
    made = tr
  end)
  return made
end

-- Probe: report exactly which CET APIs this game build exposes. ---------------
function IG.probe()
  local a = {}
  a.game = type(Game) == "table"
  a.player = false
  if a.game then pcall(function() a.player = Game.GetPlayer() ~= nil end) end
  a.ex = type(exEntitySpawner) == "table"
  a.spawnRecord = a.ex and type(exEntitySpawner.SpawnRecord) == "function" or false
  a.spawn = a.ex and type(exEntitySpawner.Spawn) == "function" or false
  a.find = a.game and type(Game.FindEntityByID) == "function" or false
  a.teleport = a.game and type(Game.GetTeleportationFacility) == "function" or false
  a.worldTransform = type(WorldTransform) == "table" and type(WorldTransform.new) == "function" or false
  a.vector4 = type(Vector4) == "table" and type(Vector4.new) == "function" or false
  a.euler = type(EulerAngles) == "table" and type(EulerAngles.new) == "function" or false
  a.registerInput = type(registerInput) == "function"
  a.static = a.game and type(Game.GetStaticEntitySystem) == "function" or false
  IG.api = a
  if a.spawnRecord then IG.spawner = "exEntitySpawner.SpawnRecord + Spawn + Despawn"
  elseif a.spawn then IG.spawner = "exEntitySpawner.Spawn (path templates only)"
  elseif a.static then IG.spawner = "Game.GetStaticEntitySystem (Codeware)"
  else IG.spawner = "UNAVAILABLE — PHANTOM cockpit-only mode" end
  return a
end

local function inPlay()
  local ok, yes = pcall(function()
    if type(Game) ~= "table" or type(Game.GetPlayer) ~= "function" then return false end
    if not Game.GetPlayer() then return false end
    if type(Game.GetSystemRequestsHandler) == "function" then
      local r = Game.GetSystemRequestsHandler()
      if r then
        if type(r.IsPreGame) == "function" and r:IsPreGame() then return false end
        if type(r.IsGamePaused) == "function" and r:IsGamePaused() then return false end
      end
    end
    return true
  end)
  return ok and yes == true
end
IG.inPlay = inPlay

-- Entity helpers ------------------------------------------------------------
local function spawnRecord(rec, x, y, z, deg)
  local tr = worldTransform(x, y, z, deg)
  if not tr then return nil end
  local id = nil
  if IG.api.spawnRecord then
    pcall(function() id = exEntitySpawner.SpawnRecord(rec, tr, "") end)
  end
  return id
end
local function spawnPath(path, x, y, z, deg)
  local tr = worldTransform(x, y, z, deg)
  if not tr or not IG.api.spawn then return nil end
  local id = nil
  pcall(function() id = exEntitySpawner.Spawn(path, tr, "") end)
  return id
end
local function resolve(id)
  if not id then return nil end
  local e = nil
  pcall(function() if IG.api.find then e = Game.FindEntityByID(id) end end)
  return e
end
local function moveEntity(e, x, y, z, deg)
  if not e then return false end
  local ok = pcall(function()
    local tr = e:GetWorldTransform()
    tr:SetPosition(vec(x, y, z))
    if type(tr.SetOrientationEuler) == "function" then tr:SetOrientationEuler(euler(deg)) end
    e:SetWorldTransform(tr)
  end)
  return ok
end
local function despawn(id, e)
  e = e or resolve(id)
  if e and type(exEntitySpawner) == "table" and type(exEntitySpawner.Despawn) == "function" then
    pcall(function() exEntitySpawner.Despawn(e) end)
  end
end

-- Rotated signature-part offsets around the core chassis. --------------------
local function partOffset(i, total)
  local a = (i - 1) * (2 * math.pi / math.max(1, total))
  local r = IG.ph.partSpread
  return { x = math.cos(a) * r, y = math.sin(a) * r,
           z = 1.4 + (i % 3) * 0.75, phase = a }
end
local function rotated(off, yaw)
  local c, s = math.cos(yaw), math.sin(yaw)
  return { x = off.x * c - off.y * s, y = off.x * s + off.y * c, z = off.z }
end

-- Deploy / undeploy ---------------------------------------------------------
function IG.deploy()
  IG.probe()
  if not inPlay() then
    IG.status = "BLOCKED — load a save in the open world first"
    iglog(IG.status)
    return false
  end
  if IG.active then IG.undeploy() end
  local pos, fwd, deg = nil, nil, 0
  pcall(function()
    local p = Game.GetPlayer()
    if not p then return end
    pos = p:GetWorldPosition()
    if type(p.GetWorldForward) == "function" then fwd = p:GetWorldForward() end
    local o = nil
    if type(p.GetWorldOrientation) == "function" then
      o = p:GetWorldOrientation()
      if o and type(o.ToEulerAngles) == "function" then deg = (o:ToEulerAngles().yaw) or 0 end
    end
    if deg == 0 and type(p.GetWorldYaw) == "function" then
      local wy = p:GetWorldYaw()
      if wy then deg = wy * 180 / math.pi end
    end
  end)
  if not pos then
    IG.status = "BLOCKED — player position unavailable"
    iglog(IG.status)
    return false
  end
  if not fwd then fwd = { x = math.sin(math.rad(deg)), y = math.cos(math.rad(deg)), z = 0 } end
  IG.baseZ = (pos.z or 0) + IG.ph.spawnHeight
  IG.pos = {
    x = (pos.x or 0) + (fwd.x or 0) * IG.ph.spawnDistance,
    y = (pos.y or 0) + (fwd.y or 0) * IG.ph.spawnDistance,
    z = IG.baseZ
  }
  IG.yaw = math.rad(deg or 0)
  IG.vy = 0; IG.gait = 0; IG.heat = 0.34; IG.kills = 0; IG.venting = 0
  IG.clock = 0; IG.lastTeleport = -1; IG.lastThreat = 0
  IG.lastTelemetry = 1 / math.max(0.2, IG.ph.telemetryHz)  -- recompute on the first frame
  IG.parts = {}; IG.hostiles = {}; IG.templateIds = {}
  IG.core = nil; IG.coreId = nil; IG.usedTemplates = false
  IG.active = true; IG.phantom = false

  local d = yawDeg(IG.yaw)
  IG.coreId = spawnRecord(IG.coreRecord, IG.pos.x, IG.pos.y, IG.pos.z, d)
  if not IG.coreId and IG.api.spawn then
    for _, t in ipairs(IG.cfg.entityTemplates) do
      local id = spawnPath(t.path, IG.pos.x + (t.slot == "reactor" and 0.6 or 0),
        IG.pos.y, IG.pos.z + (t.slot == "bus" and 1.2 or 0), d)
      if id then
        table.insert(IG.templateIds, id)
        iglog("Fallback .ent template spawned: " .. tostring(t.name))
      end
    end
    IG.usedTemplates = #IG.templateIds > 0
  end
  if not IG.coreId and not IG.usedTemplates then
    IG.phantom = true
    IG.status = "PHANTOM — no spawner / no record; cockpit-only flight"
    iglog("Spawn unavailable or record rejected. " .. IG.status)
  else
    IG.status = "DEPLOYED — " .. tostring(IG.coreName) ..
      (IG.usedTemplates and " (.ent template fallback)" or " (vanilla record)")
    iglog(IG.status .. " · record " .. tostring(IG.coreRecord))
  end
  local n = math.min(IG.partCount, IG.ph.maxParts, #IG.cfg.partRecords)
  for i = 1, n do
    local pr = IG.cfg.partRecords[i]
    local off = rotated(partOffset(i, n), IG.yaw)
    local id = spawnRecord(pr.id, IG.pos.x + off.x, IG.pos.y + off.y, IG.pos.z + off.z, d)
    table.insert(IG.parts, { id = id, entity = nil, off = partOffset(i, n), rec = pr.id, slot = pr.slot, name = pr.name })
  end
  iglog(tostring(n) .. " in-game signature part records queued (" .. tostring(#IG.cfg.partRecords) .. " configured)")
  pcall(function() IG.telemetry = MF.compute(MF.activeDesignId) end)
  if IG.cockpitLock then iglog("Cockpit lock ENGAGED — " .. IG.cameraMode .. " camera, F7 emergency undeploy") end
  return true
end

function IG.undeploy()
  despawn(IG.coreId, IG.core)
  for _, p in ipairs(IG.parts or {}) do despawn(p.id, p.entity) end
  for _, h in ipairs(IG.hostiles or {}) do despawn(h.id, h.entity) end
  for _, id in ipairs(IG.templateIds or {}) do despawn(id, nil) end
  local n = #(IG.parts or {}) + #(IG.hostiles or {}) + #(IG.templateIds or {}) + (IG.coreId and 1 or 0)
  IG.coreId = nil; IG.core = nil; IG.parts = {}; IG.hostiles = {}; IG.templateIds = {}
  IG.active = false; IG.phantom = false; IG.usedTemplates = false
  IG.keys = {}; IG.vy = 0; IG.autopilot = false
  IG.status = "STANDBY"
  iglog("UNDEPLOYED — " .. tostring(n) .. " spawned entities despawned, cockpit lock released")
  return true
end
IG.emergency = function() return IG.undeploy() end

-- Consequences: RCS / ECM actually spawn or break in-world locks. -----------
function IG.spawnHostile()
  if #IG.hostiles >= IG.ph.maxHostiles then return false end
  local a = IG.gait * 0.37 + #IG.hostiles * 2.1
  local x = IG.pos.x + math.cos(a) * IG.ph.threatDistance
  local y = IG.pos.y + math.sin(a) * IG.ph.threatDistance
  local id = spawnRecord(IG.cfg.hostileRecord, x, y, IG.pos.z + 1, yawDeg(IG.yaw) + 180)
  if not id then return false end
  table.insert(IG.hostiles, { id = id, entity = nil, x = x, y = y })
  iglog("RCS / EMISSION LOCK — in-game drone acquired you (" .. tostring(#IG.hostiles) .. " active)")
  return true
end
function IG.breakLock()
  local h = table.remove(IG.hostiles or {}, 1)
  if not h then return false end
  despawn(h.id, h.entity)
  IG.kills = IG.kills + 1
  iglog("ECM / SALVO — lock broken, hostile despawned (" .. tostring(IG.kills) .. " total)")
  return true
end
IG.fire = function() return IG.breakLock() end
IG.vent = function()
  IG.heat = math.max(0.34, IG.heat - 0.38)
